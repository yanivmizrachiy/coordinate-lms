function choose(bank: readonly string[], seed: number): string {
  const safe = Number.isFinite(seed) ? Math.abs(Math.trunc(seed)) : 0;
  return bank[safe % bank.length] ?? bank[0] ?? '';
}

export function teacherVoice(
  state: TeacherFeedbackState,
  attempts: number,
  questionIndex: number,
): string {
  const seed = questionIndex * 11 + attempts * 7;

  if (state === 'correct') {
    return choose(attempts <= 1 ? FIRST_TRY : CORRECTED, seed);
  }
  if (state === 'partial') return choose(PARTIAL, seed);
  if (state === 'locked') return choose(LOCKED, seed);
  return choose(WRONG, seed);
}

export function pageScoreVoice(score: number, pageNumber: number): string {
  const safeScore = Math.max(0, Math.min(100, Math.round(score)));
  const seed = pageNumber * 17 + safeScore * 5;

  if (safeScore >= 90) return choose(PAGE_EXCELLENT, seed);
  if (safeScore >= 75) return choose(PAGE_GOOD, seed);
  if (safeScore >= 60) return choose(PAGE_MIDDLE, seed);
  if (safeScore >= 40) return choose(PAGE_NEEDS_WORK, seed);
  return choose(PAGE_LOW, seed);
}
