import type { AnswerKey } from './types';

export type ProvenAnswerClassification =
  | 'reviewed-explicit'
  | 'deterministic-mathematical';

export interface ProvenAnswerProof {
  answers: string[];
  classification: ProvenAnswerClassification;
  sourceEvidence: string;
  targetSignature: string;
}

type ProofTuple = readonly [
  targetId: string,
  targetSignature: string,
  answers: readonly string[],
  classification?: ProvenAnswerClassification,
];

function pageProofs(
  sourceEvidence: string,
  entries: readonly ProofTuple[],
): Record<string, ProvenAnswerProof> {
  return Object.fromEntries(
    entries.map(([targetId, targetSignature, answers, classification]) => [
      targetId,
      {
        answers: [...answers],
        classification: classification ?? 'deterministic-mathematical',
        sourceEvidence,
        targetSignature,
      },
    ]),
  );
}

